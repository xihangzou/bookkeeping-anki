def main() -> int:
    with NOTES.open("r", encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh, delimiter="\t")
        fieldnames = list(reader.fieldnames or [])
        rows = list(reader)

    changed = 0
    for row in rows:
        note_id = row["ID"]
        if note_id in TEXT_OVERRIDES and row["Text"] != TEXT_OVERRIDES[note_id]:
            row["Text"] = TEXT_OVERRIDES[note_id]
            changed += 1

    with NOTES.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames, delimiter="\t", lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)

    approved = [r for r in rows if r["Status"] == "approved"]
    indices = [{int(i) for i, _ in CLOZE_RE.findall(r["Text"])} for r in approved]
    cards = sum(len(x) for x in indices)
    spans = sum(len(CLOZE_RE.findall(r["Text"])) for r in approved)
    print(f"FND-00 v1.6 migration applied: changed={changed} approved={len(approved)} cards={cards} cloze_spans={spans}")
    return 0


